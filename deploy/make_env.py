"""Create deploy/.env.production from the local .env files (run on your own machine).

    python deploy/make_env.py --ip 13.250.1.2

- Keeps your secrets (Stripe, Keycloak client, Cloudinary, mail, Groq...) from
  major-guide/.env and agentic-ai/apps/.env.
- Points every service at its docker compose container name.
- Generates new passwords for MongoDB, RabbitMQ and the TURN server.
- Never prints a secret. The output file is git-ignored.
"""
import argparse
import re
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / ".env.production"


def read_env(path: Path) -> dict:
    values = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$", line)
        if match:
            values[match.group(1)] = match.group(2).strip()
    return values


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def quote(value: str) -> str:
    """Single quotes stop docker compose from expanding $ inside secrets."""
    if value[:1] == '"' and value[-1:] == '"' and "$" not in value:
        return value  # double quotes keep \n escapes working (e.g. GOOGLE_PRIVATE_KEY)
    value = unquote(value)
    if value == "" or re.fullmatch(r"[A-Za-z0-9_./:@,+=?{}-]+", value):
        return value
    return "'" + value.replace("'", "") + "'"


def password(n=24):
    return secrets.token_urlsafe(n).replace("-", "x").replace("_", "y")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ip", required=True, help="Elastic IP of the EC2 server, e.g. 13.250.1.2")
    parser.add_argument("--domain", help="Default: <ip-with-dashes>.sslip.io")
    args = parser.parse_args()
    domain = args.domain or args.ip.replace(".", "-") + ".sslip.io"
    origin = f"https://{domain}"

    env = read_env(ROOT / "agentic-ai" / "apps" / ".env")
    env.update(read_env(ROOT / ".env"))  # backend values win on shared keys

    # Keep generated passwords when the file is re-created (data already uses them).
    old = read_env(OUT)
    mongo_pw = unquote(old.get("MONGO_ROOT_PASSWORD", "")) or password()
    rabbit_pw = unquote(old.get("RABBITMQ_PASSWORD", "")) or password()
    turn_pw = unquote(old.get("WEBRTC_TURN_CREDENTIAL", "")) or password(18)

    overrides = {
        # used by docker-compose.prod.yml itself
        "DOMAIN": domain,
        "PUBLIC_IP": args.ip,
        "PRIVATE_IP": unquote(old.get("PRIVATE_IP", "")) or "0.0.0.0",
        "MONGO_ROOT_USER": "root",
        "MONGO_ROOT_PASSWORD": mongo_pw,
        "RABBITMQ_USER": "majorguide",
        "RABBITMQ_PASSWORD": rabbit_pw,
        # infrastructure
        "MONGODB_URI": f"mongodb://root:{mongo_pw}@mongodb:27017/?authSource=admin",
        "REDIS_HOST": "redis",
        "REDIS_PORT": "6379",
        "RABBITMQ_SERVER_HOST": f"amqp://majorguide:{rabbit_pw}@rabbitmq:5672",
        "KEYCLOAK_HOST": "http://keycloak:8080",
        # service discovery (TCP / gRPC hosts = compose service names)
        "SLOT_SERVICE_HOST": "slot",
        "USER_ACCESS_SERVICE_HOST": "user-access",
        "MEDIA_SERVICE_HOST": "media",
        "AUTHORIZER_SERVICE_HOST": "authorizer",
        "BOOKING_SERVICE_HOST": "booking",
        "CHAT_SERVICE_HOST": "chat",
        "TCP_CHAT_SERVICE_HOST": "chat",
        "AI_AGENT_SERVICE_HOST": "agentic-ai",
        "PYTHON_SERVICE_HOST": "agentic-ai",
        "AGENTIC_AI_SERVICE_URL": "http://agentic-ai:8000",
        "CAREER_MODEL_ENABLED": "true",
        "CAREER_MODEL_TIMEOUT_MS": "4000",
        # public URLs
        "STRIPE_SUCCESS_URL": f"{origin}/payment-success.html?session_id={{CHECKOUT_SESSION_ID}}",
        "STRIPE_CANCEL_URL": f"{origin}/my-bookings?payment=cancelled",
        "VNP_RETURN_URL": f"{origin}/payment-success.html",
        # video call
        "WEBRTC_STUN_URL": "stun:stun.l.google.com:19302",
        "WEBRTC_TURN_URL": f"turn:{args.ip}:3478",
        "WEBRTC_TURN_USERNAME": "majorguide",
        "WEBRTC_TURN_CREDENTIAL": turn_pw,
        # agentic-ai
        "QDRANT_URL": "http://qdrant:6333",
        "BFF_INTERNAL_URL": "http://bff:3300/api/v2",
        "CORS_ALLOWED_ORIGINS": origin,
        "APP_ENV": "production",
        "HF_HOME": "/models",
    }
    env.update(overrides)

    required = ["KEYCLOAK_REALM", "KEYCLOAK_CLIENT_ID", "KEYCLOAK_CLIENT_SECRET", "STRIPE_SECRET_KEY",
                "AGENTIC_INTERNAL_TOKEN", "GLOBAL_PREFIX", "PORT", "USER_ACCESS_SERVICE_DB_NAME"]
    missing = [key for key in required if not unquote(env.get(key, ""))]

    lines = ["# Generated by deploy/make_env.py - contains secrets, do not commit."]
    lines += [f"{key}={quote(value)}" for key, value in env.items()]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} ({len(env)} variables) for https://{domain}")
    if missing:
        print("WARNING - empty values, check them:", ", ".join(missing))


if __name__ == "__main__":
    main()
